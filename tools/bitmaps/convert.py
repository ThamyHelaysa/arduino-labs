#!/usr/bin/env python3
"""Converts black, white and red PNGs into a .h with Adafruit GFX bitmaps (one black and one red layer each)."""

import argparse
import re
import struct
import sys
import zlib
from pathlib import Path

SIGNATURE = b"\x89PNG\r\n\x1a\n"
CHANNELS = {2: 3, 6: 4}  # color type: RGB, RGBA


def paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    return b if pb <= pc else c


def read_png(path):
    """Returns (width, height, rows), where each row is a list of (r, g, b, a)."""
    data = Path(path).read_bytes()
    if not data.startswith(SIGNATURE):
        raise ValueError(f"{path}: not a PNG")
    pos, idat, header = len(SIGNATURE), b"", None
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b"IHDR":
            header = struct.unpack(">IIBBBBB", body)
        elif kind == b"IDAT":
            idat += body
        elif kind == b"IEND":
            break
    if not header:
        raise ValueError(f"{path}: missing IHDR")
    width, height, depth, color, _, _, interlace = header
    if depth != 8 or color not in CHANNELS or interlace:
        raise ValueError(f"{path}: only 8-bit, non-interlaced RGB or RGBA PNGs are supported")

    step = CHANNELS[color]
    stride = width * step
    raw = zlib.decompress(idat)
    previous = bytearray(stride)
    rows = []
    for y in range(height):
        start = y * (stride + 1)
        kind, line = raw[start], bytearray(raw[start + 1:start + 1 + stride])
        for i in range(stride):
            left = line[i - step] if i >= step else 0
            up = previous[i]
            up_left = previous[i - step] if i >= step else 0
            predictor = (0, left, up, (left + up) // 2, paeth(left, up, up_left))[kind]
            line[i] = (line[i] + predictor) & 0xFF
        rows.append([tuple(line[x:x + step]) + (255,) * (4 - step) for x in range(0, stride, step)])
        previous = line
    return width, height, rows


def classify(pixel):
    """Maps a pixel to 'red', 'black' or None (white)."""
    r, g, b, a = pixel
    if a < 128:
        return None
    if r >= 128 and g < 128 and b < 128:
        return "red"
    return "black" if (r + g + b) / 3 < 128 else None


def pack(rows, layer):
    """Packs one layer MSB first, each row padded to whole bytes, as Adafruit GFX drawBitmap expects."""
    out = []
    for row in rows:
        for x in range(0, len(row), 8):
            byte = 0
            for bit, pixel in enumerate(row[x:x + 8]):
                if classify(pixel) == layer:
                    byte |= 0x80 >> bit
            out.append(byte)
    return out


def c_array(name, values):
    lines = [", ".join(f"0x{v:02x}" for v in values[i:i + 16]) for i in range(0, len(values), 16)]
    return f"const uint8_t {name}[] PROGMEM = {{\n  " + ",\n  ".join(lines) + "\n};\n"


def scale_up(rows, factor):
    """Nearest-neighbor upscale, so pixel art keeps its hard edges."""
    return [[pixel for pixel in row for _ in range(factor)] for row in rows for _ in range(factor)]


def convert(paths, name, scale=1):
    size, parts = None, []
    for path in paths:
        width, height, rows = read_png(path)
        rows, width, height = scale_up(rows, scale), width * scale, height * scale
        if size and size != (width, height):
            raise ValueError(f"{path}: is {width}x{height}, the others are {size[0]}x{size[1]}")
        size = (width, height)
        stem = re.sub(r"\W", "_", Path(path).stem)
        for layer in ("black", "red"):
            parts.append(c_array(f"{name}_{stem}_{layer}", pack(rows, layer)))
    upper = name.upper()
    head = (f"// Generated by tools/bitmaps/convert.py. Do not edit by hand.\n#pragma once\n\n"
            f"const int {upper}_WIDTH  = {size[0]};\nconst int {upper}_HEIGHT = {size[1]};\n\n")
    return head + "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pngs", nargs="+", help="PNG files, all the same size")
    parser.add_argument("--name", required=True, help="prefix for the C names, e.g. cat")
    parser.add_argument("--output", required=True, help=".h file to write")
    parser.add_argument("--scale", type=int, default=1, help="whole-number upscale factor, e.g. 4 turns 16x16 into 64x64")
    args = parser.parse_args()
    if args.scale < 1:
        parser.error("--scale must be 1 or more")
    try:
        Path(args.output).write_text(convert(args.pngs, args.name, args.scale))
    except (ValueError, OSError, zlib.error) as error:
        sys.exit(f"Error: {error}")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
